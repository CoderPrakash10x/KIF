const { PDFDocument, rgb, StandardFonts } = require('pdf-lib');
const cloudinary = require('../config/cloudinary');
const { User } = require('../models');
const { sendEmail, escapeHtml } = require('../utils/email');

const NAVY = rgb(0.06, 0.09, 0.16);   // #0F172A
const BLUE = rgb(0.15, 0.39, 0.92);   // #2563EB
const BG = rgb(0.973, 0.98, 0.988);   // #F8FAFC
const MUTED = rgb(0.4, 0.45, 0.55);

// ---------------------------------------------------------------------------
// SHARED BASE — builds the visual certificate shell. Callers pass in the
// title/body text; this function owns fonts, layout, colors, and upload.
// ---------------------------------------------------------------------------
// StandardFonts only encode WinAnsi; anything else (Devanagari, emoji) used to throw and fail the whole certificate.
// Replace unencodable glyphs so a certificate is still produced. Follow-up: embed a Unicode TTF via @pdf-lib/fontkit.
const winAnsiSafe = (t) => String(t ?? '').replace(/[^\x20-\x7E\xA0-\xFF\u2013\u2014\u2018\u2019\u201C\u201D\u2022\u2026\u20AC]/g, '?');

async function buildCertificatePdf({ headerText, subHeaderText, bodyLines, footerLeft, footerRight, folder, publicId }) {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([842, 595]); // A4 landscape
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  const regularFont = await pdfDoc.embedFont(StandardFonts.Helvetica);

  page.drawRectangle({ x: 0, y: 0, width: 842, height: 595, color: BG });
  page.drawRectangle({ x: 20, y: 20, width: 802, height: 555, borderColor: BLUE, borderWidth: 3 });

  page.drawText('KIPM INNOVATION FOUNDATION', { x: 240, y: 500, size: 22, font: boldFont, color: NAVY });
  page.drawText(winAnsiSafe(headerText), { x: 220, y: 460, size: 18, font: boldFont, color: BLUE });
  if (subHeaderText) {
    page.drawText(winAnsiSafe(subHeaderText), { x: 260, y: 435, size: 12, font: regularFont, color: NAVY });
  }

  let y = 400;
  for (const line of bodyLines) {
    page.drawText(winAnsiSafe(line.text), { x: line.x || 220, y, size: line.size || 12, font: line.bold ? boldFont : regularFont, color: NAVY });
    y -= line.gap || 25;
  }

  page.drawText(winAnsiSafe(footerLeft), { x: 40, y: 45, size: 9, font: regularFont, color: MUTED });
  page.drawText(footerRight, { x: 550, y: 45, size: 9, font: regularFont, color: MUTED });

  const pdfBytes = await pdfDoc.save();
  const url = await uploadBufferToCloudinary(pdfBytes, publicId, folder);
  return url;
}

function uploadBufferToCloudinary(buffer, publicId, folder) {
  return new Promise((resolve, reject) => {
    const stream = cloudinary.uploader.upload_stream(
      { resource_type: 'raw', public_id: publicId, folder },
      (err, result) => (err ? reject(err) : resolve(result.secure_url))
    );
    stream.end(buffer);
  });
}

// ---------------------------------------------------------------------------
// NO-DUES CERTIFICATE (unchanged behavior, now using shared base)
// ---------------------------------------------------------------------------
async function generateNoDuesCertificate(noDuesRecord) {
  const user = await User.findById(noDuesRecord.userId);
  if (!user) throw new Error('User not found for certificate generation');

  const url = await buildCertificatePdf({
    headerText: 'NO-DUES CLEARANCE CERTIFICATE',
    bodyLines: [
      { text: 'This is to certify that', x: 350, size: 12 },
      { text: user.name, x: 350, size: 20, bold: true, gap: 30 },
      { text: `(${user.role}${user.department ? ' - ' + user.department : ''}${user.startupName ? ' - ' + user.startupName : ''})`, x: 300, size: 12, gap: 30 },
      { text: 'has no pending dues across Cabin, Hardware, and Room resource modules', x: 220, size: 12, gap: 25 },
      { text: 'as per KIF-RMS records, and is cleared for exit.', x: 280, size: 12 },
    ],
    footerLeft: `Certificate ID: NDC-${noDuesRecord._id.toString().slice(-8).toUpperCase()} | Issued: ${new Date().toDateString()}`,
    footerRight: 'Digitally generated by KIF-RMS — Admin verified',
    folder: 'kif-rms/certificates/no-dues',
    publicId: `${user._id}-${Date.now()}.pdf`,
  });

  return { url };
}

// ---------------------------------------------------------------------------
// EVENT PARTICIPATION CERTIFICATE
// ---------------------------------------------------------------------------
async function generateEventCertificate(user, event) {
  const url = await buildCertificatePdf({
    headerText: 'CERTIFICATE OF PARTICIPATION',
    subHeaderText: `Event: ${event.title}`,
    bodyLines: [
      { text: 'This is to certify that', x: 350, size: 12 },
      { text: user.name, x: 350, size: 20, bold: true, gap: 30 },
      { text: `has successfully participated in "${event.title}"`, x: 220, size: 12, gap: 25 },
      { text: `held on ${event.date.toDateString()} at ${event.venue}.`, x: 260, size: 12 },
    ],
    footerLeft: `Certificate ID: EVC-${event._id.toString().slice(-6).toUpperCase()}-${user._id.toString().slice(-6).toUpperCase()}`,
    footerRight: 'Digitally generated by KIF-RMS',
    folder: 'kif-rms/certificates/events',
    publicId: `${event._id}-${user._id}-${Date.now()}.pdf`,
  });

  return url;
}

async function emailCertificate(user, subject, message, certificateUrl) {
  return sendEmail({
    to: user.email,
    subject,
    html: `
      <div style="font-family: Inter, sans-serif; max-width: 480px; margin: auto;">
        <h2 style="color:#0F172A;">${escapeHtml(subject)}</h2>
        <p style="color:#1E293B;">${escapeHtml(message)}</p>
        <a href="${certificateUrl}" style="display:inline-block;padding:12px 24px;background:#2563EB;
           color:white;text-decoration:none;border-radius:8px;margin-top:12px;">Download Certificate</a>
      </div>`,
  });
}

module.exports = { generateNoDuesCertificate, generateEventCertificate, emailCertificate };